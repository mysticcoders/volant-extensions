#!/usr/bin/env python3
"""Checks that the license notices for third-party code compiled into the modules are present and current.

- RUST-LICENSES (generated by cargo-about) names every crates.io package in Cargo.lock at its locked
  version, so a `cargo update` or a new dependency fails until the notice is regenerated.
- Every extension built with Javy (its build.sh pins JAVY_VERSION) carries the Javy, QuickJS-ng,
  rquickjs, Javy plugin crate and wasi-libc notices; every extension built with wasi-sdk and
  MicroPython (its build.sh pins WASI_SDK_TAG) carries the MicroPython and wasi-libc notices.
- tools/new-extension.py copies the same notices into a new TypeScript or Python extension.

docs/dependency-audit.md says how each notice was produced and how to regenerate it.

Usage: tools/check-licenses.py [ROOT]
"""
import importlib.util
import pathlib
import re
import sys
import tomllib


def load_new_extension(root):
    """Imports tools/new-extension.py, whose name is not a valid module name."""
    sys.dont_write_bytecode = True
    spec = importlib.util.spec_from_file_location("new_extension", root / "tools/new-extension.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def rust_problems(root):
    """Lists crates.io packages in Cargo.lock that RUST-LICENSES does not name at their locked version."""
    notice = root / "RUST-LICENSES"
    if not notice.is_file():
        return ["RUST-LICENSES is missing"]
    listed = set(re.findall(r"^  (\S+) (\S+)$", notice.read_text(), re.MULTILINE))
    packages = tomllib.loads((root / "Cargo.lock").read_text()).get("package", [])
    return [f"RUST-LICENSES does not list {package['name']} {package['version']}; regenerate it with cargo-about"
            for package in packages
            if package.get("source", "").startswith("registry+") and (package["name"], package["version"]) not in listed]


def folder_problems(root, typescript_licenses, python_licenses):
    """Lists extension folders missing a notice their toolchain requires."""
    problems = []
    for build in sorted(root.glob("*/build.sh")):
        script = build.read_text()
        required = (typescript_licenses if "JAVY_VERSION=" in script else ()) + \
                   (python_licenses if "WASI_SDK_TAG=" in script else ())
        for name in required:
            if not (build.parent / name).is_file() or not (build.parent / name).read_text().strip():
                problems.append(f"{build.parent.name}/{name} is missing or empty")
    return problems


def main(arguments):
    root = pathlib.Path(arguments[0]).resolve() if arguments else pathlib.Path(__file__).resolve().parent.parent
    new_extension = load_new_extension(root)
    typescript, python = new_extension.TYPESCRIPT_LICENSES, new_extension.PYTHON_LICENSES
    problems = rust_problems(root) + folder_problems(root, typescript, python)
    for files, licenses, language in ((new_extension.TYPESCRIPT_FILES, typescript, "TypeScript"),
                                      (new_extension.PYTHON_FILES, python, "Python")):
        problems += [f"tools/new-extension.py does not copy {name} into a new {language} extension"
                     for name in licenses if name not in files]
    for problem in problems:
        print(problem, file=sys.stderr)
    if problems:
        sys.exit(1)
    print("check-licenses: every notice is present and RUST-LICENSES covers Cargo.lock")


if __name__ == "__main__":
    main(sys.argv[1:])

#!/usr/bin/env python3
"""Writes sfsymbols/src/symbols.tsv, the SF Symbols name list the extension embeds, from the metadata
macOS ships in its CoreGlyphs bundle. Only facts about each symbol are kept: its name, the release
that introduced it, its categories, its search keywords, the names it replaced and, for symbols Apple
restricts, what they may only refer to. No glyph, image or asset from the bundle is read or copied.

The file is committed, so building the extension never needs this Mac's bundle; run this again on a
newer macOS to pick up new symbols, then ./build.sh.

Usage: sfsymbols/generate.py [RESOURCES_FOLDER]
"""
import pathlib
import plistlib
import re
import sys

RESOURCES = pathlib.Path("/System/Library/CoreServices/CoreGlyphs.bundle/Contents/Resources")
OUTPUT = pathlib.Path(__file__).resolve().parent / "src" / "symbols.tsv"
PUBLIC_NAME = re.compile(r"^[a-z0-9][a-z0-9.]*$")
RESTRICTION = re.compile(r"refer to (.+?)\.?$")
PLATFORMS = ("iOS", "macOS", "tvOS", "visionOS", "watchOS")
SKIPPED_CATEGORIES = {"all", "whatsnew"}
CATEGORY_TITLES = {
    "draw": "Draw", "variable": "Variable", "multicolor": "Multicolor", "communication": "Communication",
    "weather": "Weather", "maps": "Maps", "objectsandtools": "Objects & Tools", "devices": "Devices",
    "cameraandphotos": "Camera & Photos", "gaming": "Gaming", "connectivity": "Connectivity",
    "transportation": "Transportation", "automotive": "Automotive", "accessibility": "Accessibility",
    "privacyandsecurity": "Privacy & Security", "human": "Human", "home": "Home", "fitness": "Fitness",
    "nature": "Nature", "editing": "Editing", "textformatting": "Text Formatting", "media": "Media",
    "keyboard": "Keyboard", "commerce": "Commerce", "time": "Time", "health": "Health", "shapes": "Shapes",
    "arrows": "Arrows", "indices": "Indices", "math": "Math",
}


def load(resources, name):
    """One of the bundle's property lists; the .strings files are binary property lists too."""
    with open(resources / name, "rb") as handle:
        return plistlib.load(handle)


def clean(text):
    """Text safe for one tab-separated field."""
    return re.sub(r"[\t\n\r]+", " ", text).strip()


def main():
    resources = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else RESOURCES
    availability = load(resources, "name_availability.plist")
    order = load(resources, "symbol_order.plist")
    categories = load(resources, "symbol_categories.plist")
    keywords = load(resources, "symbol_search.plist")
    aliases = load(resources, "name_aliases.strings")
    restrictions = load(resources, "symbol_restrictions.strings")
    category_keys = [entry["key"] for entry in load(resources, "categories.plist") if entry["key"] not in SKIPPED_CATEGORIES]
    unknown = [key for key in category_keys if key not in CATEGORY_TITLES]
    if unknown:
        sys.exit(f"Add a title for the new categories: {unknown}")

    releases = availability["year_to_release"]
    names = [name for name in order if PUBLIC_NAME.match(name) and name in availability["symbols"]]
    current = set(names)
    formerly = {}
    for old, new in aliases.items():
        if PUBLIC_NAME.match(old) and new in current and old not in current:
            formerly.setdefault(new, []).append(old)
    used_releases = sorted({availability["symbols"][name] for name in names}, key=lambda key: [int(part) for part in key.split(".")])

    lines = ["# SF Symbols names, generated by sfsymbols/generate.py from macOS's CoreGlyphs metadata. Do not edit."]
    for release in used_releases:
        versions = releases[release]
        lines.append("\t".join(["@release", release] + [f"{platform} {versions[platform]}" for platform in PLATFORMS if platform in versions]))
    for key in category_keys:
        lines.append("\t".join(["@category", key, CATEGORY_TITLES[key]]))
    for name in names:
        restriction = restrictions.get(name, "")
        found = RESTRICTION.search(restriction) if restriction else None
        fields = [
            name,
            availability["symbols"][name],
            ",".join(key for key in categories.get(name, []) if key in CATEGORY_TITLES),
            ",".join(clean(word) for word in keywords.get(name, []) if "," not in word),
            clean(found.group(1)) if found else ("restricted" if restriction else ""),
            ",".join(sorted(formerly.get(name, []))),
        ]
        lines.append("\t".join(fields))
    OUTPUT.write_text("\n".join(lines) + "\n")
    print(f"Wrote {len(names)} symbols ({OUTPUT.stat().st_size} bytes) to {OUTPUT}")


if __name__ == "__main__":
    main()
